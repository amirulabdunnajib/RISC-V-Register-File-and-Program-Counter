);
    localparam c_PC_INITIAL_VALUE = 32'h0040_0000;

    /* Program Counter (PC) */
    reg [31:0] r_PC_Output;

    always @(posedge i_Clk or posedge i_Rst) begin
        if(i_Rst) begin
            r_PC_Output <= c_PC_INITIAL_VALUE;
